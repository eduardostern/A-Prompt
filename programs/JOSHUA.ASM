ORG 100H
START:	LXI SP,STACK
	CALL CLEAR
	MVI C,9
	LXI D,HEAD
	CALL 5
	CALL ASKPL
	JMP NEWGM

CLEAR:	MVI C,9
	LXI D,CLRS
	CALL 5
	RET

ASKPL:	MVI C,9
	LXI D,ASK
	CALL 5
ASK1:	MVI C,1
	CALL 5
	CPI 31H
	JZ ASK1P
	CPI 32H
	JZ ASK2P
	CPI 5AH
	JZ ASKZ
	CPI 7AH
	JZ ASKZ
	JMP ASK1
ASKZ:	MVI C,1
	CALL 5
	CPI 45H
	JZ ASKZE
	CPI 65H
	JZ ASKZE
	JMP ASK1
ASKZE:	MVI C,1
	CALL 5
	CPI 52H
	JZ ASKZER
	CPI 72H
	JZ ASKZER
	JMP ASK1
ASKZER:	MVI C,1
	CALL 5
	CPI 4FH
	JZ ASK0P
	CPI 6FH
	JZ ASK0P
	JMP ASK1
ASK0P:	MVI A,0
	STA MODE
	CALL CRLF
	CALL INITZ
	RET
ASK1P:	MVI A,1
	STA MODE
	CALL CRLF
	RET
ASK2P:	MVI A,2
	STA MODE
	CALL CRLF
	RET

NEWGM:	MVI A,0
	STA MOVES
	MVI A,1
	STA PLR
	LXI H,BRD
	MVI B,9
	MVI A,0
NGL:	MOV M,A
	INX H
	DCR B
	JNZ NGL
	JMP TURN

TURN:	CALL DRAW
	LDA MODE
	CPI 0
	JNZ TURN0
	CALL AUTOD
TURN0:	LDA MODE
	CPI 1
	JZ TURN1
	CPI 2
	JZ TURN2
	JMP TURNC
TURN1:	LDA PLR
	CPI 2
	JZ TURNC
TURN2:	CALL HUMAN
	STA IDX
	CALL PLACE
	JMP AFTER
TURNC:	CALL COMPM
AFTER:	CALL CHKWIN
	CPI 0
	JNZ GOVER
	LDA MOVES
	CPI 9
	JZ DRWGM
	LDA PLR
	CPI 1
	JNZ SET2
	MVI A,2
	STA PLR
	JMP TURN
SET2:	MVI A,1
	STA PLR
	JMP TURN

HUMAN:	LDA MODE
	CPI 1
	JNZ H2
	LXI D,PM1
	JMP HPOUT
H2:	LDA PLR
	CPI 1
	JNZ H3
	LXI D,PM2
	JMP HPOUT
H3:	LXI D,PM3
HPOUT:	MVI C,9
	CALL 5
HREAD:	MVI C,1
	CALL 5
	CPI 31H
	JC HERR
	CPI 3AH
	JNC HERR
	SUI 31H
	STA IDX
	LDA IDX
	MOV E,A
	MVI D,0
	LXI H,BRD
	DAD D
	MOV A,M
	ORA A
	JNZ HERR
	LDA IDX
	RET
HERR:	MVI C,9
	LXI D,INV
	CALL 5
	JMP HUMAN

PLACE:	LDA IDX
	MOV E,A
	MVI D,0
	LXI H,BRD
	DAD D
	LDA PLR
	MOV M,A
	LDA MOVES
	INR A
	STA MOVES
	RET

COMPM:	LDA MOVES
	ORA A
	JZ RNDMV
	LDA PLR
	CALL FINDW
	CPI 0FFH
	JNZ CMPLAY
	LDA PLR
	CPI 1
	JNZ CMOP2
	MVI A,2
	JMP CMOP
CMOP2:	MVI A,1
CMOP:	CALL FINDW
	CPI 0FFH
	JNZ CMPLAY
	LDA BRD+4
	ORA A
	JNZ CM1
	MVI A,4
	JMP CMPLAY
CM1:	LDA BRD+4
	CPI 2
	JNZ CM2
	LDA BRD+0
	CPI 1
	JNZ CMX1
	LDA BRD+8
	CPI 1
	JZ CM5
CMX1:	LDA BRD+2
	CPI 1
	JNZ CM2
	LDA BRD+6
	CPI 1
	JZ CM5
	JMP CM2
CM2:	LDA BRD+0
	ORA A
	JNZ CM3
	MVI A,0
	JMP CMPLAY
CM3:	LDA BRD+2
	ORA A
	JNZ CM4
	MVI A,2
	JMP CMPLAY
CM4:	LDA BRD+6
	ORA A
	JNZ CM6
	MVI A,6
	JMP CMPLAY
CM6:	LDA BRD+8
	ORA A
	JNZ CM5
	MVI A,8
	JMP CMPLAY
CM5:	LDA BRD+1
	ORA A
	JNZ CM7
	MVI A,1
	JMP CMPLAY
CM7:	LDA BRD+3
	ORA A
	JNZ CM8
	MVI A,3
	JMP CMPLAY
CM8:	LDA BRD+5
	ORA A
	JNZ CM9
	MVI A,5
	JMP CMPLAY
CM9:	MVI A,7
CMPLAY:	STA IDX
	CALL PLACE
	RET

RNDMV:	CALL GETSEC
RNDL:	CPI 9
	JC RNDS
	SUI 9
	JMP RNDL
RNDS:	STA IDX
	CALL PLACE
	RET

FINDW:	STA TMPPL
	MVI A,0
	STA IDX
FWLOOP:	LDA IDX
	CPI 9
	JNC FWNN
	LDA IDX
	MOV E,A
	MVI D,0
	LXI H,BRD
	DAD D
	MOV A,M
	ORA A
	JNZ FWNEXT
	LDA TMPPL
	MOV M,A
	CALL CHKWIN
	STA TMPWIN
	LDA IDX
	MOV E,A
	MVI D,0
	LXI H,BRD
	DAD D
	MVI M,0
	LDA TMPWIN
	CPI 0
	JZ FWNEXT
	MOV C,A
	LDA TMPPL
	CMP C
	JZ FWFND
FWNEXT:	LDA IDX
	INR A
	STA IDX
	JMP FWLOOP
FWFND:	LDA IDX
	RET
FWNN:	MVI A,0FFH
	RET

CHKWIN:	LDA BRD+0
	ORA A
	JZ WN1
	MOV B,A
	LDA BRD+1
	CMP B
	JNZ WN1
	LDA BRD+2
	CMP B
	JNZ WN1
	MOV A,B
	RET
WN1:	LDA BRD+3
	ORA A
	JZ WN2
	MOV B,A
	LDA BRD+4
	CMP B
	JNZ WN2
	LDA BRD+5
	CMP B
	JNZ WN2
	MOV A,B
	RET
WN2:	LDA BRD+6
	ORA A
	JZ WN3
	MOV B,A
	LDA BRD+7
	CMP B
	JNZ WN3
	LDA BRD+8
	CMP B
	JNZ WN3
	MOV A,B
	RET
WN3:	LDA BRD+0
	ORA A
	JZ WN4
	MOV B,A
	LDA BRD+3
	CMP B
	JNZ WN4
	LDA BRD+6
	CMP B
	JNZ WN4
	MOV A,B
	RET
WN4:	LDA BRD+1
	ORA A
	JZ WN5
	MOV B,A
	LDA BRD+4
	CMP B
	JNZ WN5
	LDA BRD+7
	CMP B
	JNZ WN5
	MOV A,B
	RET
WN5:	LDA BRD+2
	ORA A
	JZ WN6
	MOV B,A
	LDA BRD+5
	CMP B
	JNZ WN6
	LDA BRD+8
	CMP B
	JNZ WN6
	MOV A,B
	RET
WN6:	LDA BRD+0
	ORA A
	JZ WN7
	MOV B,A
	LDA BRD+4
	CMP B
	JNZ WN7
	LDA BRD+8
	CMP B
	JNZ WN7
	MOV A,B
	RET
WN7:	LDA BRD+2
	ORA A
	JZ WN8
	MOV B,A
	LDA BRD+4
	CMP B
	JNZ WN8
	LDA BRD+6
	CMP B
	JNZ WN8
	MOV A,B
	RET
WN8:	XRA A
	RET

DRAW:	MVI C,9
	LXI D,CLRS
	CALL 5
	MVI C,9
	LXI D,HEAD
	CALL 5
	CALL DRWBRD
	RET

DRWBRD:	LXI D,SP1
	CALL PSTR
	LDA BRD+0
	CALL PCELL
	LXI D,BAR
	CALL PSTR
	LDA BRD+1
	CALL PCELL
	LXI D,BAR
	CALL PSTR
	LDA BRD+2
	CALL PCELL
	CALL CRLF
	LXI D,SEP
	CALL PSTR
	LXI D,SP1
	CALL PSTR
	LDA BRD+3
	CALL PCELL
	LXI D,BAR
	CALL PSTR
	LDA BRD+4
	CALL PCELL
	LXI D,BAR
	CALL PSTR
	LDA BRD+5
	CALL PCELL
	CALL CRLF
	LXI D,SEP
	CALL PSTR
	LXI D,SP1
	CALL PSTR
	LDA BRD+6
	CALL PCELL
	LXI D,BAR
	CALL PSTR
	LDA BRD+7
	CALL PCELL
	LXI D,BAR
	CALL PSTR
	LDA BRD+8
	CALL PCELL
	CALL CRLF
	RET

PCELL:	CALL CHR
	MOV E,A
	MVI C,2
	CALL 5
	RET

CHR:	PUSH H
	PUSH D
	MOV E,A
	MVI D,0
	LXI H,MARKS
	DAD D
	MOV A,M
	POP D
	POP H
	RET

PSTR:	MVI C,9
	CALL 5
	RET

CRLF:	MVI C,9
	LXI D,CRLFS
	CALL 5
	RET

PAUSE:	LHLD DELAY
	MOV A,H
	ORA L
	JZ PDONE
PIN:	DCX H
	MOV A,H
	ORA L
	JNZ PIN
PDONE:	RET

AUTOD:	CALL CHKTIM
	JNZ AUTOT
	CALL PAUSE
	RET
AUTOT:	JMP MOVMSG

CHKTIM:	CALL GETSEC
	MOV B,A
	LDA STRTS
	MOV C,A
	MOV A,B
	SUB C
	JNC CHK1
	ADI 60
CHK1:	CPI 15
	JC CHKNO
	MVI A,1
	ORA A
	RET
CHKNO:	XRA A
	RET

GETSEC:	MVI C,105
	LXI D,TIMBUF
	CALL 5
	MOV B,A
	ANI 0F0H
	RRC
	RRC
	RRC
	RRC
	MOV C,A
	ADD A
	ADD A
	ADD C
	ADD A
	MOV C,A
	MOV A,B
	ANI 0FH
	ADD C
	RET

SLOWDN:	LHLD DELAY
	MOV A,H
	ORA L
	JZ SLOWR
	MOV A,H
	ORA A
	RAR
	MOV H,A
	MOV A,L
	RAR
	MOV L,A
	SHLD DELAY
SLOWR:	RET

INITZ:	CALL GETSEC
	STA STRTS
	LXI H,0FFFFH
	SHLD DELAY
	RET

GOVER:	STA TMPWIN
	CALL DRAW
	LDA MODE
	CPI 0
	JZ GOV0
	LDA TMPWIN
	CPI 1
	JNZ GW2
	LXI D,XWINS
	JMP GWP
GW2:	LXI D,OWINS
GWP:	MVI C,9
	CALL 5
	JMP AGAIN
GOV0:	CALL CHKTIM
	JNZ MOVMSG
	CALL SLOWDN
	JMP NEWGM

DRWGM:	CALL DRAW
	LDA MODE
	CPI 0
	JZ DRW0
	MVI C,9
	LXI D,DMSG
	CALL 5
	JMP AGAIN
DRW0:	CALL CHKTIM
	JNZ MOVMSG
	CALL SLOWDN
	JMP NEWGM

MOVMSG:	MVI C,9
	LXI D,MOVIE
	CALL 5
	JMP AGAIN

AGAIN:	MVI C,9
	LXI D,AGN
	CALL 5
AGN1:	MVI C,1
	CALL 5
	CPI 59H
	JZ AGNY
	CPI 79H
	JZ AGNY
	CPI 4EH
	JZ EXIT
	CPI 6EH
	JZ EXIT
	JMP AGN1
AGNY:	LDA MODE
	CPI 0
	JNZ NEWGM
	CALL INITZ
	JMP NEWGM
EXIT:	JMP 0

CLRS:	DB 1BH,'[2J',1BH,'[H','$'
HEAD:	DB 'GREETINGS, PROFESSOR FALKEN.',13,10,13,10
	DB 'FALKEN',27H,'S MAZE',13,10
	DB 'TIC-TAC-TOE',13,10,13,10,'$'
ASK:	DB 'NUMBER OF PLAYERS (ZERO,1 OR 2)? $'
PM1:	DB 'YOUR MOVE (1-9): $'
PM2:	DB 'PLAYER 1 (X): $'
PM3:	DB 'PLAYER 2 (O): $'
INV:	DB 13,10,'INVALID MOVE',13,10,'$'
XWINS:	DB 13,10,'X WINS!',13,10,'$'
OWINS:	DB 13,10,'O WINS!',13,10,'$'
DMSG:	DB 13,10,'DRAW GAME',13,10,'$'
MOVIE:	DB 13,10,'A STRANGE GAME.',13,10
	DB 'THE ONLY WINNING MOVE IS NOT TO PLAY.',13,10,'$'
AGN:	DB 13,10,'PLAY AGAIN? (Y/N): $'
CRLFS:	DB 13,10,'$'
SP1:	DB ' $'
BAR:	DB ' | $'
SEP:	DB '---+---+---',13,10,'$'
MARKS:	DB ' ','X','O'
BRD:	DS 9
MOVES:	DB 0
MODE:	DB 1
PLR:	DB 1
IDX:	DB 0
TMPPL:	DB 0
TMPWIN:	DB 0
STRTS:	DB 0
DELAY:	DW 0
TIMBUF:	DS 4
	DS 64
STACK:
	END START
