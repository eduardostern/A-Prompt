;	JOSHUA - the WOPR from WarGames (1983) for CP/M 2.2 on A-Prompt.
;
;	LOGON: JOSHUA, then SHALL WE PLAY A GAME? Pick GLOBAL THERMONUCLEAR
;	WAR, or TIC-TAC-TOE with ZERO players to make it play itself, faster
;	and faster, until it runs every war scenario and learns.
;
;	The first version (tic-tac-toe, zero players, the closing line) was
;	written by DeepSeek V4.1 Flash on the A-Prompt AI board (ATDT AI,
;	then P); Claude added the logon, the game list, the war montage,
;	random openings and the gradual speed-up.
;
;	Needs an ANSI/VT100 terminal. Timing uses BDOS 105 (CP/M 3 T_GET),
;	which A-Prompt provides; the busy-loop delays assume 4 MHz.

BDOS	EQU	5
CONIN	EQU	1
CONOUT	EQU	2
PSTR	EQU	9
RDLINE	EQU	10
TGET	EQU	105
CR	EQU	13
LF	EQU	10
ESC	EQU	1BH
APOS	EQU	27H
ZEROS	EQU	25		; seconds of zero-player games before the montage
MOVE0	EQU	350		; ms per move in the first zero-player game
CHARMS	EQU	22		; ms per character when WOPR types

	ORG	100H
START:	LXI	SP,STACK
	CALL	SEED

; ---- logon ----------------------------------------------------------

LOGON:	CALL	CLEAR
LOG1:	LXI	D,LOGMSG
	CALL	PRINT
	CALL	GETLN
	LXI	H,JNAME
	CALL	MATCH
	JZ	GREET
	LDA	TRIES
	INR	A
	STA	TRIES
	LXI	D,NOTREC
	CALL	TYPE
	LDA	TRIES
	CPI	2
	JC	LOG1
	LXI	D,HINT
	CALL	PRINT
	JMP	LOG1

GREET:	CALL	SEED		; the logon took human time: stir the seed
	LXI	D,GREETS
	CALL	TYPE

; ---- the game list --------------------------------------------------

MENU:	LXI	D,SHALL
	CALL	TYPE
	LXI	D,GLIST1
	CALL	PRINT
	LXI	D,GLIST2
	CALL	PRINT
MENU1:	LXI	D,WHICH
	CALL	PRINT
	CALL	GETLN
	LDA	LBUF+1
	ORA	A
	JZ	MENU1
	LDA	LBUF+2
	CPI	'T'
	JZ	TTT
	CPI	'Q'
	JZ	QUIT
	CALL	NUMBER
	CPI	15
	JZ	GTW
	CPI	7
	JZ	CHESS
	CPI	1
	JC	MENU1
	CPI	16
	JNC	MENU1
	LXI	D,NOTAV
	CALL	TYPE
	JMP	MENU1

CHESS:	LXI	D,LATER
	CALL	TYPE
	JMP	MENU1

QUIT:	LXI	D,BYE
	CALL	TYPE
	JMP	0

; ---- global thermonuclear war ---------------------------------------

GTW:	LXI	D,PREFER
	CALL	TYPE
	CALL	GETLN
	LXI	D,FINE
	CALL	TYPE
	LXI	D,SIDE
	CALL	TYPE
GTW1:	CALL	GETLN
	LDA	LBUF+2
	CPI	'1'
	JZ	GTW2
	CPI	'2'
	JZ	GTW2
	LXI	D,CHOOSE
	CALL	PRINT
	JMP	GTW1
GTW2:	LXI	D,AWAIT
	CALL	TYPE
	LXI	H,1500
	CALL	MS
	JMP	WAR

; ---- tic-tac-toe ----------------------------------------------------

TTT:	CALL	CLEAR
	LXI	D,TTTHD
	CALL	PRINT
	LXI	D,ASK
	CALL	PRINT
ASK1:	CALL	GETLN
	LDA	LBUF+2
	CPI	'1'
	JZ	ASK1P
	CPI	'2'
	JZ	ASK2P
	CPI	'0'
	JZ	ASK0P
	LXI	H,ZNAME
	CALL	MATCH
	JZ	ASK0P
	LXI	D,ASK
	CALL	PRINT
	JMP	ASK1
ASK0P:	XRA	A
	STA	MODE
	CALL	INITZ
	JMP	NEWGM
ASK1P:	MVI	A,1
	STA	MODE
	JMP	NEWGM
ASK2P:	MVI	A,2
	STA	MODE

NEWGM:	XRA	A
	STA	MOVES
	MVI	A,1
	STA	PLR
	LXI	H,BRD
	MVI	B,9
NGL:	MVI	M,0
	INX	H
	DCR	B
	JNZ	NGL
	LHLD	GAMES
	INX	H
	SHLD	GAMES

TURN:	CALL	DRAW
	LDA	MODE
	ORA	A
	JNZ	TURN0
	CALL	CHKTIM		; zero players: time for the montage?
	JNZ	WAR
	CALL	PAUSE
	JMP	TURNC
TURN0:	CPI	1
	JNZ	TURNH
	LDA	PLR
	CPI	2
	JZ	TURNC
TURNH:	CALL	HUMAN
	CALL	PLACE
	JMP	AFTER
TURNC:	CALL	COMPM
AFTER:	CALL	CHKWIN
	ORA	A
	JNZ	GOVER
	LDA	MOVES
	CPI	9
	JZ	DRWGM
	LDA	PLR
	XRI	3		; 1 <-> 2
	STA	PLR
	JMP	TURN

HUMAN:	LDA	MODE
	CPI	1
	LXI	D,PM1
	JZ	HPOUT
	LDA	PLR
	CPI	1
	LXI	D,PM2
	JZ	HPOUT
	LXI	D,PM3
HPOUT:	CALL	PRINT
	MVI	C,CONIN
	CALL	BDOS
	CPI	'1'
	JC	HERR
	CPI	'9'+1
	JNC	HERR
	SUI	'1'
	STA	IDX
	CALL	EMPTY
	JNZ	HERR
	RET
HERR:	LXI	D,INV
	CALL	PRINT
	JMP	HUMAN

PLACE:	LDA	IDX
	MOV	E,A
	MVI	D,0
	LXI	H,BRD
	DAD	D
	LDA	PLR
	MOV	M,A
	LDA	MOVES
	INR	A
	STA	MOVES
	RET

; The computer: win, block, centre, the anti-fork edge, then a corner
; and an edge picked at random, so every game can differ.
COMPM:	LDA	MOVES
	ORA	A
	JZ	RNDMV
	LDA	PLR
	CALL	FINDW
	CPI	0FFH
	JNZ	CMPLAY
	LDA	PLR
	XRI	3
	CALL	FINDW
	CPI	0FFH
	JNZ	CMPLAY
	MVI	A,4
	CALL	EMPTY
	JZ	CMPLAY
	LDA	BRD+4		; we hold the centre, they hold opposite
	MOV	B,A		; corners: take an edge, not a corner
	LDA	PLR
	CMP	B
	JNZ	CMCOR
	MOV	A,B
	XRI	3
	MOV	B,A
	LDA	BRD+0
	CMP	B
	JNZ	CMX1
	LDA	BRD+8
	CMP	B
	JZ	CMEDGE
CMX1:	LDA	BRD+2
	CMP	B
	JNZ	CMCOR
	LDA	BRD+6
	CMP	B
	JZ	CMEDGE
CMCOR:	LXI	H,CORN
	CALL	TRYL
	JC	CMPLAY
CMEDGE:	LXI	H,EDGE
	CALL	TRYL
	JC	CMPLAY
	LXI	H,CORN
	CALL	TRYL
CMPLAY:	STA	IDX
	JMP	PLACE

RNDMV:	MVI	B,9
	CALL	RNDN
	JMP	CMPLAY

; TRYL: HL = 4 squares; tries them from a random start. A = the first
; empty one with carry set, or carry clear if all are taken.
TRYL:	PUSH	H
	MVI	B,4
	CALL	RNDN
	MOV	C,A
	POP	H
	MVI	B,4
TRYL1:	PUSH	H
	MOV	A,C
	ANI	3
	MOV	E,A
	MVI	D,0
	DAD	D
	MOV	A,M
	CALL	EMPTY
	POP	H
	JZ	TRYOK
	INR	C
	DCR	B
	JNZ	TRYL1
	ORA	A
	RET
TRYOK:	STC
	RET

; EMPTY: A = square; Z if it is free. A is kept.
EMPTY:	MOV	E,A
	MVI	D,0
	LXI	H,BRD
	DAD	D
	MOV	A,M
	ORA	A
	MOV	A,E
	RET

; FINDW: A = player; returns the square that wins for them, or 0FFH.
FINDW:	STA	TMPPL
	XRA	A
	STA	IDX
FWLOOP:	LDA	IDX
	CPI	9
	JNC	FWNN
	CALL	EMPTY
	JNZ	FWNEXT
	LDA	TMPPL
	MOV	M,A
	CALL	CHKWIN
	MOV	C,A
	LDA	IDX
	CALL	EMPTY		; points HL at the square again
	MVI	M,0
	LDA	TMPPL
	CMP	C
	JZ	FWFND
FWNEXT:	LDA	IDX
	INR	A
	STA	IDX
	JMP	FWLOOP
FWFND:	LDA	IDX
	RET
FWNN:	MVI	A,0FFH
	RET

; CHKWIN: A = the winner (1 or 2), or 0.
CHKWIN:	LXI	H,LINES
	MVI	C,8
CW1:	MOV	A,M
	CALL	CELL
	ORA	A
	JZ	CWNEXT
	MOV	B,A
	INX	H
	MOV	A,M
	CALL	CELL
	CMP	B
	JNZ	CWN1
	INX	H
	MOV	A,M
	CALL	CELL
	CMP	B
	JNZ	CWN2
	MOV	A,B
	RET
CWNEXT:	INX	H
CWN1:	INX	H
CWN2:	INX	H
	DCR	C
	JNZ	CW1
	XRA	A
	RET

; CELL: A = square; A = what is in it. Keeps BC, HL.
CELL:	PUSH	H
	MOV	E,A
	MVI	D,0
	LXI	H,BRD
	DAD	D
	MOV	A,M
	POP	H
	RET

DRAW:	CALL	CLEAR
	LXI	D,TTTHD
	CALL	PRINT
	LDA	MODE
	ORA	A
	JNZ	DRAW1
	LXI	D,GAMEN
	CALL	PRINT
	LHLD	GAMES
	CALL	PDEC
	CALL	CRLF
	CALL	CRLF
DRAW1:	LXI	H,BRD
	SHLD	CPTR
	MVI	B,3
DRROW:	PUSH	B
	LXI	D,SP1
	CALL	PRINT
	CALL	PCELL
	LXI	D,BAR
	CALL	PRINT
	CALL	PCELL
	LXI	D,BAR
	CALL	PRINT
	CALL	PCELL
	CALL	CRLF
	POP	B
	DCR	B
	RZ
	PUSH	B
	LXI	D,SEP
	CALL	PRINT
	POP	B
	JMP	DRROW

; PCELL: prints the mark of the next square (CPTR) and moves on.
PCELL:	LHLD	CPTR
	MOV	A,M
	INX	H
	SHLD	CPTR
	MOV	E,A
	MVI	D,0
	LXI	H,MARKS
	DAD	D
	MOV	E,M
	MVI	C,CONOUT
	JMP	BDOS

GOVER:	STA	TMPWIN
	CALL	DRAW
	LDA	MODE
	ORA	A
	JZ	NEXTZ
	LDA	TMPWIN
	CPI	1
	LXI	D,XWINS
	JZ	GOV1
	LXI	D,OWINS
GOV1:	CALL	PRINT
	JMP	AGAIN

DRWGM:	CALL	DRAW
	LDA	MODE
	ORA	A
	JZ	NEXTZ
	LXI	D,DMSG
	CALL	PRINT
	JMP	AGAIN

; Zero players: the next game, a quarter faster than the last.
NEXTZ:	CALL	CHKTIM
	JNZ	WAR
	LHLD	DELAY
	MOV	D,H
	MOV	E,L
	CALL	SHR16
	CALL	SHR16
	MOV	A,E		; DELAY - DELAY/4
	SUB	L
	MOV	L,A
	MOV	A,D
	SBB	H
	MOV	H,A
	SHLD	DELAY
	JMP	NEWGM

AGAIN:	LXI	D,AGN
	CALL	PRINT
AGN1:	MVI	C,CONIN
	CALL	BDOS
	ANI	5FH
	CPI	'Y'
	JZ	AGNY
	CPI	'N'
	JNZ	AGN1
	CALL	CRLF
	JMP	MENU
AGNY:	LDA	MODE
	ORA	A
	CZ	INITZ
	JMP	NEWGM

INITZ:	CALL	GETSEC
	STA	STRTS
	LXI	H,MOVE0
	SHLD	DELAY
	LXI	H,0
	SHLD	GAMES
	RET

PAUSE:	LHLD	DELAY
	JMP	MS

; CHKTIM: NZ once ZEROS seconds have passed since INITZ.
CHKTIM:	CALL	GETSEC
	MOV	B,A
	LDA	STRTS
	MOV	C,A
	MOV	A,B
	SUB	C
	JNC	CHK1
	ADI	60
CHK1:	CPI	ZEROS
	JC	CHKNO
	ORI	1
	RET
CHKNO:	XRA	A
	RET

; ---- the war montage and the lesson --------------------------------

WAR:	CALL	CLEAR
	LXI	H,450
	SHLD	DELAY
	MVI	A,4		; four runs through the scenarios
	STA	PASS
WARP:	LXI	H,SCEN
WARL:	MOV	A,M
	ORA	A
	JZ	WARNX
	PUSH	H
	LXI	D,SCNMSG
	CALL	PRINT
	POP	H
	CALL	PZSTR		; the scenario's name, padded
	PUSH	H
	LXI	D,WINNER
	CALL	PRINT
	LHLD	DELAY		; each a little faster
	PUSH	H
	CALL	MS
	POP	H
	MOV	D,H
	MOV	E,L
	CALL	SHR16
	CALL	SHR16
	CALL	SHR16
	CALL	SHR16
	MOV	A,E		; DELAY - DELAY/16
	SUB	L
	MOV	L,A
	MOV	A,D
	SBB	H
	MOV	H,A
	SHLD	DELAY
	POP	H
	JMP	WARL
WARNX:	LDA	PASS
	DCR	A
	STA	PASS
	JNZ	WARP

	CALL	CLEAR		; the screens go dark
	LXI	H,2500
	CALL	MS
	LXI	D,LESSON
	CALL	TYPE
	LXI	H,1500
	CALL	MS
	LXI	D,CHESSQ
	CALL	TYPE
	JMP	MENU1

; PZSTR: prints the 0-terminated name at HL in a 24-column field;
; HL ends past the 0.
PZSTR:	MVI	B,24
PZ1:	MOV	A,M
	INX	H
	ORA	A
	JZ	PZPAD
	PUSH	H
	PUSH	B
	MOV	E,A
	MVI	C,CONOUT
	CALL	BDOS
	POP	B
	POP	H
	DCR	B
	JMP	PZ1
PZPAD:	MOV	A,B
	ORA	A
	RZ
	PUSH	H
	PUSH	B
	MVI	E,' '
	MVI	C,CONOUT
	CALL	BDOS
	POP	B
	POP	H
	DCR	B
	JMP	PZPAD

; ---- helpers --------------------------------------------------------

CLEAR:	LXI	D,CLRS
PRINT:	MVI	C,PSTR
	JMP	BDOS

CRLF:	LXI	D,CRLFS
	JMP	PRINT

; TYPE: prints the $-string at DE a character at a time, as WOPR does.
TYPE:	LDAX	D
	CPI	'$'
	RZ
	PUSH	D
	MOV	E,A
	MVI	C,CONOUT
	CALL	BDOS
	LXI	H,CHARMS
	CALL	MS
	POP	D
	INX	D
	JMP	TYPE

; MS: waits HL milliseconds (at 4 MHz).
MS:	MOV	A,H
	ORA	L
	RZ
MS1:	MVI	A,210
MS2:	DCR	A
	NOP
	JNZ	MS2
	DCX	H
	MOV	A,H
	ORA	L
	JNZ	MS1
	RET

; SHR16: HL = HL / 2.
SHR16:	ORA	A
	MOV	A,H
	RAR
	MOV	H,A
	MOV	A,L
	RAR
	MOV	L,A
	RET

; GETLN: reads a line into LBUF, upper case, 0 after the last character.
GETLN:	LXI	D,LBUF
	MVI	C,RDLINE
	CALL	BDOS
	LXI	H,LBUF+1
	MOV	B,M
	INX	H
	INR	B
GL1:	DCR	B
	JZ	GL2
	MOV	A,M
	CPI	61H		; a
	JC	GL3
	CPI	7BH		; past z
	JNC	GL3
	ANI	5FH
	MOV	M,A
GL3:	INX	H
	JMP	GL1
GL2:	MVI	M,0
	RET

; MATCH: Z if the line read equals the 0-terminated text at HL.
MATCH:	LXI	D,LBUF+2
MT1:	LDAX	D
	CMP	M
	RNZ
	ORA	A
	RZ
	INX	D
	INX	H
	JMP	MT1

; NUMBER: A = the line read as a number, 0 if it is not one.
NUMBER:	LXI	H,LBUF+2
	MVI	B,0
NM1:	MOV	A,M
	ORA	A
	JZ	NMEND
	SUI	'0'
	JC	NMBAD
	CPI	10
	JNC	NMBAD
	MOV	C,A
	MOV	A,B		; B = B*10 + digit
	ADD	A
	ADD	A
	ADD	B
	ADD	A
	ADD	C
	MOV	B,A
	INX	H
	JMP	NM1
NMEND:	MOV	A,B
	RET
NMBAD:	XRA	A
	RET

; PDEC: prints HL in decimal.
PDEC:	MVI	B,0		; no digit printed yet
	LXI	D,0D8F0H	; -10000
	CALL	PDIG
	LXI	D,0FC18H	; -1000
	CALL	PDIG
	LXI	D,0FF9CH	; -100
	CALL	PDIG
	LXI	D,0FFF6H	; -10
	CALL	PDIG
	MVI	B,1
	LXI	D,0FFFFH	; -1
PDIG:	MVI	C,'0'-1
PD1:	INR	C
	DAD	D
	JC	PD1
	MOV	A,L		; undo the last subtraction
	SUB	E
	MOV	L,A
	MOV	A,H
	SBB	D
	MOV	H,A
	MOV	A,C
	CPI	'0'
	JNZ	PD2
	MOV	A,B
	ORA	A
	RZ
PD2:	MVI	B,1
	PUSH	H
	PUSH	B
	MOV	E,C
	MVI	C,CONOUT
	CALL	BDOS
	POP	B
	POP	H
	RET

; GETSEC: A = the clock's seconds, binary (T_GET gives BCD).
GETSEC:	MVI	C,TGET
	LXI	D,TIMBUF
	CALL	BDOS
	MOV	B,A
	ANI	0F0H
	RRC
	RRC
	RRC
	RRC
	MOV	C,A
	ADD	A
	ADD	A
	ADD	C
	ADD	A
	MOV	C,A
	MOV	A,B
	ANI	0FH
	ADD	C
	RET

; SEED: stirs the clock (minutes and seconds) into the random seed.
SEED:	CALL	GETSEC
	MOV	E,A
	LDA	TIMBUF+3
	MOV	D,A
	LHLD	RNDV
	DAD	D
	SHLD	RNDV
	RET

; RNDN: B = n; A = a random number 0..n-1.
RNDN:	PUSH	H
	PUSH	D
	LHLD	RNDV		; RNDV = RNDV * 5 + 3619H
	MOV	D,H
	MOV	E,L
	DAD	H
	DAD	H
	DAD	D
	LXI	D,3619H
	DAD	D
	SHLD	RNDV
	MOV	A,H
	POP	D
	POP	H
RN1:	CMP	B
	RC
	SUB	B
	JMP	RN1

