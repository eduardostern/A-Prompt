	JMP	BDOS

; MKCRC: tables for CRC-16/XMODEM (polynomial 1021H), high bytes at
; TABHI and low bytes at TABLO, one page each.
MKCRC:	MVI	C,0
MK1:	MOV	H,C
	MVI	L,0
	MVI	B,8
MK2:	DAD	H
	JNC	MK3
	MOV	A,H
	XRI	10H
	MOV	H,A
	MOV	A,L
	XRI	21H
	MOV	L,A
MK3:	DCR	B
	JNZ	MK2
	MOV	E,C
	MVI	D,TABHI SHR 8
	MOV	A,H
	STAX	D
	INR	D
	MOV	A,L
	STAX	D
	INR	C
	JNZ	MK1
	RET

; CRCUP: adds A to the CRC. Keeps BC, DE and HL.
CRCUP:	PUSH	H
	PUSH	D
	LHLD	CRC
	XRA	H
	MOV	E,A
	MVI	D,TABHI SHR 8
	LDAX	D
	XRA	L
	MOV	H,A
	INR	D
	LDAX	D
	MOV	L,A
	SHLD	CRC
	POP	D
	POP	H
	RET

