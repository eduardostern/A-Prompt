; ERRCHK: after a failed header or subpacket (A = 1 for cancel).
ERRCHK:	CPI	1
	LXI	D,SCANCL
	JZ	FAIL
	LDA	ERRS
	INR	A
	STA	ERRS
	CPI	10
	RC
	LXI	D,SERRS
	JMP	FAIL

; RECV: waits up to B seconds for a modem byte. A = byte with carry
; clear, or carry set on timeout. Keeps BC, DE and HL.
RECV:	IN	MSTAT
	ANI	RXRDY
	JZ	RSLOW
	IN	MDATA
	ORA	A
	RET
RSLOW:	PUSH	B
	PUSH	D
	PUSH	H
	MOV	A,B
	STA	TLEFT
	CALL	GETSEC
	STA	TSEC
RS1:	LXI	H,2000		; polls between clock reads
RS2:	IN	MSTAT
	ANI	RXRDY
	JNZ	RSGOT
	DCX	H
	MOV	A,H
	ORA	L
	JNZ	RS2
	CALL	CHKABT
	CALL	GETSEC
	LXI	H,TSEC
	CMP	M
	JZ	RS1
	MOV	M,A
	LXI	H,TLEFT
	DCR	M
	JNZ	RS1
	POP	H
	POP	D
	POP	B
	STC
	RET
RSGOT:	IN	MDATA
	POP	H
	POP	D
	POP	B
	ORA	A
	RET

GETSEC:	MVI	C,TGET		; A = seconds (BCD)
	LXI	D,TBUF
	JMP	BDOS

PUT:	OUT	MDATA		; keeps A
	RET

PUTS:	MOV	A,M		; sends the string at HL up to a 0
	ORA	A
	RZ
	CALL	PUT
	INX	H
	JMP	PUTS

; CHKABT: Ctrl-X or Ctrl-C on the keyboard cancels the transfer.
CHKABT:	CALL	CONST
	ORA	A
	RZ
	CALL	CONIN
	CPI	CAN
	JZ	ABORT
	CPI	CTRLC
	RNZ
ABORT:	LXI	D,SABORT
	JMP	FAIL

DOT:	PUSH	B
	PUSH	D
	PUSH	H
	MVI	E,'.'
	MVI	C,CONOUT
	CALL	BDOS
	POP	H
	POP	D
	POP	B
	RET

; PFNAME: prints the FCB's file name.
PFNAME:	LXI	H,FCB+1
	MVI	B,11
PF1:	MOV	A,B
	CPI	3
	JNZ	PF2
	PUSH	B
	PUSH	H
	MVI	E,'.'
	MVI	C,CONOUT
	CALL	BDOS
	POP	H
	POP	B
PF2:	MOV	A,M
	ANI	7FH
	CPI	' '
	JZ	PF3
	PUSH	B
	PUSH	H
	MOV	E,A
	MVI	C,CONOUT
	CALL	BDOS
	POP	H
	POP	B
PF3:	INX	H
	DCR	B
	JNZ	PF1
	LXI	D,SCRLF
	JMP	PRINT

; FAIL: cancels the other end, keeps what was received, prints DE.
FAIL:	PUSH	D
	LXI	H,SCANIT
	CALL	PUTS
	CALL	FLUSH
	POP	D
EXITM:	CALL	PRINT
	JMP	0

