#!/usr/bin/env node
/**
 * Embeds the files from ./programs as base64 in a TypeScript module so the
 * emulator is a single self-contained bundle with no runtime fetches.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, extname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'programs');
const outFile = join(root, 'src', 'assets', 'builtin-programs.ts');

const files = readdirSync(dir)
  .filter((f) => /\.(com|asm|txt|sub|hex)$/i.test(f))
  .sort();

const entries = files.map((f) => {
  const data = readFileSync(join(dir, f));
  const name = basename(f, extname(f)).toUpperCase();
  const ext = extname(f).slice(1).toUpperCase();
  return { name, ext, data: data.toString('base64') };
});

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/embed-programs.mjs - do not edit by hand.\n` +
    `// CP/M utilities (c) Digital Research, distributed under the CP/M license.\n` +
    `export interface BuiltinFile { name: string; ext: string; data: string }\n` +
    `export const BUILTIN_FILES: BuiltinFile[] = ${JSON.stringify(entries, null, 2)};\n`,
);

console.log(`embedded ${entries.length} files -> ${outFile}`);
